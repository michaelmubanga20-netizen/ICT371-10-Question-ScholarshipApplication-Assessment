

CREATE TABLE students(student_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,student_number varchar(30) NOT NULL UNIQUE,full_name text NOT NULL);
CREATE TABLE applications(
 application_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,student_id integer NOT NULL REFERENCES students(student_id),
 age_at_application integer NOT NULL CHECK(age_at_application>0),
 monthly_income numeric(12,2) NOT NULL CHECK(monthly_income>=0),
 average_mark numeric(5,2) NOT NULL CHECK(average_mark BETWEEN 0 AND 100),
 submitted_on date NOT NULL,
 status text NOT NULL DEFAULT 'PENDING' CHECK(status IN('PENDING','APPROVED','REJECTED'))
);
CREATE TABLE decision_audit(
 audit_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,application_id bigint NOT NULL REFERENCES applications(application_id),
 old_status text NOT NULL,new_status text NOT NULL,changed_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
