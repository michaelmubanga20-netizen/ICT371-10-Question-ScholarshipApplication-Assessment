CREATE OR REPLACE FUNCTION fn_scholarship_eligible(p_age integer,p_income numeric,p_mark numeric)
RETURNS boolean LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
 IF p_age IS NULL OR p_income IS NULL OR p_mark IS NULL THEN RAISE EXCEPTION 'All eligibility inputs are required'; END IF;
 IF p_age<=0 OR p_income<0 OR p_mark<0 OR p_mark>100 THEN RAISE EXCEPTION 'Invalid eligibility input'; END IF;
 RETURN p_age BETWEEN 18 AND 25 AND p_income<=3000 AND p_mark>=70;
END $$;

CREATE OR REPLACE PROCEDURE pr_assess_application(p_application_id bigint)
LANGUAGE plpgsql AS $$
DECLARE a record;
BEGIN
 SELECT * INTO a FROM applications WHERE application_id=p_application_id AND status='PENDING' FOR UPDATE;
 IF NOT FOUND THEN
  IF NOT EXISTS(SELECT 1 FROM applications WHERE application_id=p_application_id) THEN RAISE EXCEPTION 'Unknown application ID %',p_application_id;
  ELSE RAISE EXCEPTION 'Application % has already been assessed',p_application_id; END IF;
 END IF;
 UPDATE applications SET status=CASE WHEN fn_scholarship_eligible(a.age_at_application,a.monthly_income,a.average_mark)
 THEN 'APPROVED' ELSE 'REJECTED' END
 WHERE application_id=p_application_id;
END $$;

CREATE OR REPLACE FUNCTION trg_decision_audit_fn()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.status IS DISTINCT FROM NEW.status THEN
  INSERT INTO decision_audit(application_id,old_status,new_status)
  VALUES(NEW.application_id,OLD.status,NEW.status);
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER applications_status_audit AFTER UPDATE ON applications
FOR EACH ROW EXECUTE FUNCTION trg_decision_audit_fn();

CREATE OR REPLACE VIEW v_approved_applicants AS
SELECT s.student_number,s.full_name,a.average_mark,a.status
FROM applications a JOIN students s USING(student_id) WHERE a.status='APPROVED';

CREATE INDEX idx_applications_status_submitted ON applications(status,submitted_on);
EXPLAIN SELECT * FROM applications WHERE status='PENDING'
AND submitted_on BETWEEN CURRENT_DATE-30 AND CURRENT_DATE;

CREATE OR REPLACE PROCEDURE pr_assess_pending()
LANGUAGE plpgsql AS $$
DECLARE r record;
BEGIN
 FOR r IN SELECT application_id FROM applications WHERE status='PENDING' ORDER BY application_id LOOP
  CALL pr_assess_application(r.application_id);
 END LOOP;
END $$;
